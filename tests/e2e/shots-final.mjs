import { launch, shot } from './lib.mjs';
import { readFileSync } from 'node:fs';
const save = readFileSync('tests/logs/saves/beat-23.json', 'utf8');
const t = await launch({ width: 1280, height: 720, port: 4450 });
const { page } = t;
await page.waitForFunction(() => window.__AOTS__?.snapshot().assetsReady, null, { timeout: 30000 });
await page.waitForTimeout(1500);
await shot(page, 'title', 'tests/logs/screens/final');
const ok = await page.evaluate(() => { const i = document.querySelector('.title-img'); return i && i.naturalWidth; });
console.log('title image naturalWidth', ok);
await page.evaluate((s) => localStorage.setItem('aots3.cell.v1.auto', s), save);
await page.reload();
await page.waitForFunction(() => window.__AOTS__?.snapshot().assetsReady, null, { timeout: 30000 });
await page.evaluate(() => window.__AOTS__.settings({ showTutorials: false }));
await page.getByRole('button', { name: /continue/i }).first().click();
await page.waitForTimeout(150);
await shot(page, 'loading-veil', 'tests/logs/screens/final');
await page.waitForFunction(() => window.__AOTS__.snapshot().screen === 'world' && !window.__AOTS__.snapshot().loading, null, { timeout: 30000 });
await page.waitForTimeout(800);
await shot(page, 'capsule', 'tests/logs/screens/final');
console.log('errors', t.errors);
await t.close();
